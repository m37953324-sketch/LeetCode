class Task83 {
    /**
     * Удаляет повторяющиеся элементы из отсортированного связанного списка.
     *
     * Идея решения:
     * Список уже отсортирован по возрастанию, значит все одинаковые значения
     * стоят подряд. Мы проходим по списку одним указателем [current] и
     * сравниваем каждый узел со следующим за ним. Если значения совпадают —
     * значит, следующий узел дубликат, и мы «выбрасываем» его из цепочки,
     * перепрыгивая через него. Если значения различаются — просто сдвигаемся
     * на следующий узел. Голова списка никогда не удаляется, поэтому её можно
     * вернуть как есть.
     *
     * Сложность:
     * - Время:   O(n) — проходим список ровно один раз.
     * - Память:  O(1) — используем только одну дополнительную переменную.
     *
     * Стек-схема для [1, 1, 2, 3, 3]:
     *
     *   Шаг 1: current = 1, next = 1 → совпадают: 1 -> 1 -> 2 -> 3 -> 3
     *           Пропускаем дубликат: 1 ─────────> 2 -> 3 -> 3
     *           current остаётся на первом узле «1».
     *
     *   Шаг 2: current = 1, next = 2 → различаются, сдвигаемся: current = 2.
     *
     *   Шаг 3: current = 2, next = 3 → различаются, сдвигаемся: current = 3.
     *
     *   Шаг 4: current = 3, next = 3 → совпадают:
     *           3 -> 3 -> null  →  пропускаем: 3 -> null
     *           current остаётся на «3».
     *
     *   Шаг 5: current.next == null → цикл завершён.
     *
     *   Результат: 1 -> 2 -> 3
     */
    fun deleteDuplicates(head: ListNode?): ListNode? {
        // Будем двигаться по списку, начиная с головы.
        // head не трогаем — он нам понадобится для возврата.
        var current = head

        // Пока есть текущий узел и существует следующий за ним —
        // есть что сравнивать. Condition `current?.next` возвращает
        // `null` и завершает цикл, когда список пуст (current == null)
        // или мы дошли до последнего узла (next == null).
        while (current?.next != null) {
            // Безопасный вызов + `!!` гарантируют, что на этой строке
            // next точно не null (проверено условием while).
            if (current.`val` == current.next!!.`val`) {
                // Значения равны → следующий узел дубликат.
                // «Выбрасываем» его: перестраиваем ссылку current.next
                // так, чтобы она указывала на узел ПОСЛЕ дубликата.
                current.next = current.next!!.next
                // ВАЖНО: НЕ двигаем current дальше. Вдруг следующий узел
                // тоже дубликат (например, [1,1,1])? Сначала проверим его.
            } else {
                // Значения разные — дубликатов больше в этой группе нет.
                // Просто переходим к следующему узлу.
                current = current.next
            }
        }

        // Голова списка никогда не удалялась, поэтому возвращаем её.
        return head
    }
}

/**
 * Вспомогательная функция для тестов.
 * Строит связанный список из переданных значений.
 *
 * Логика построения:
 * Создаём «пустую» голову-заглушку (dummy). Её значение [0] не важно —
 * она нужна только для того, чтобы было удобно навешивать новые узлы,
 * пока список ещё пуст (не приходится обрабатывать случай «первый узел»).
 * Затем для каждого числа создаём новый узел ListNode и прицепляем его
 * в конец через current.next, а current сдвигаем на этот новый узел.
 *
 * Пример для listOfNodes(1, 1, 2):
 *
 *   dummy(0) → текущий  = dummy
 *   шаг 1: dummy(0) -> ListNode(1),  current = ListNode(1)
 *   шаг 2: ListNode(1) -> ListNode(1), current = ListNode(1)  (второй)
 *   шаг 3: ListNode(1) -> ListNode(2), current = ListNode(2)
 *
 *   Возвращаем dummy.next — то есть настоящую голову: 1 -> 1 -> 2.
 *   Сам dummy в результат не попадает.
 */
private fun listOfNodes(vararg values: Int): ListNode? {
    // Заглушка: первый узел с произвольным значением (0).
    val dummy = ListNode(0)
    // Указатель на конец уже построенной части списка.
    var current = dummy

    // По одному узлу на каждое входящее значение.
    for (v in values) {
        // Создаём узел со значением v и вешаем в конец списка.
        current.next = ListNode(v)
        // Сдвигаем указатель конца на только что добавленный узел.
        current = current.next!!
    }

    // Отдаём первый «настоящий» узел, пропуская заглушку.
    return dummy.next
}

/**
 * Вспомогательная функция для тестов.
 * Превращает связанный список в обычный Kotlin-список List<Int>,
 * чтобы его было удобно сравнивать при помощи assertEquals.
 *
 * Логика обхода:
 * Идём от головы, пока не встретим null (конец списка).
 * На каждом шаге добавляем значение текущего узла в результат
 * и переходим к следующему узлу по ссылке next.
 *
 * Пример для 1 -> 2 -> 3:
 *
 *   current = 1 → добавляем 1,  current = 2
 *   current = 2 → добавляем 2,  current = 3
 *   current = 3 → добавляем 3,  current = null → цикл завершён
 *
 *   Результат: [1, 2, 3]
 */
private fun nodesToList(node: ListNode?): List<Int> {
    // Накапливаем значения узлов здесь.
    val result = mutableListOf<Int>()
    // Указатель обхода, стартуем с переданной головы.
    var current = node

    // Пока есть текущий узел (null означает конец списка).
    while (current != null) {
        // Сохраняем значение текущего узла.
        result.add(current.`val`)
        // Переходим к следующему узлу.
        current = current.next
    }

    // Возвращаем список значений.
    return result
}

class Task83Test {

    @org.testng.annotations.Test
    fun `example 1`() {
        val head = listOfNodes(1, 1, 2)

        val result = Task83().deleteDuplicates(head)

        org.testng.Assert.assertEquals(nodesToList(result), listOf(1, 2))
    }

    @org.testng.annotations.Test
    fun `example 2`() {
        val head = listOfNodes(1, 1, 2, 3, 3)

        val result = Task83().deleteDuplicates(head)

        org.testng.Assert.assertEquals(nodesToList(result), listOf(1, 2, 3))
    }

    @org.testng.annotations.Test
    fun `empty list`() {
        val result = Task83().deleteDuplicates(null)

        org.testng.Assert.assertTrue(nodesToList(result).isEmpty())
    }
}